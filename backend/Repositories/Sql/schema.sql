-- PostgreSQL 18. Esquema v5 (OpenStreetMap y cuentas de usuario). Once tablas de dominio y una tabla técnica de versión.
-- Una base v3 o v4 existente se actualiza sola al iniciar el backend (upgrade_v4.sql y upgrade_v5.sql).
-- Ejecutar en una base/esquema vacío, dentro de una transacción.
-- Los catálogos y los puntos ilustrativos se cargan desde el backend.
CREATE TABLE departamentos (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubigeo TEXT NOT NULL UNIQUE CHECK (ubigeo ~ '^[0-9]{2}$'),
    nombre_departamento TEXT NOT NULL UNIQUE CHECK (length(trim(nombre_departamento)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE provincias (
    id_provincia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departamento INTEGER NOT NULL REFERENCES departamentos(id_departamento) ON DELETE RESTRICT ON UPDATE CASCADE,
    ubigeo TEXT NOT NULL UNIQUE CHECK (ubigeo ~ '^[0-9]{4}$'),
    nombre_provincia TEXT NOT NULL CHECK (length(trim(nombre_provincia)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (id_departamento, nombre_provincia)
);

CREATE TABLE distritos (
    id_distrito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_provincia INTEGER NOT NULL REFERENCES provincias(id_provincia) ON DELETE RESTRICT ON UPDATE CASCADE,
    ubigeo TEXT NOT NULL UNIQUE CHECK (ubigeo ~ '^[0-9]{6}$'),
    nombre_distrito TEXT NOT NULL CHECK (length(trim(nombre_distrito)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (id_provincia, nombre_distrito)
);

CREATE TABLE zonificaciones (
    id_zonificacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE CHECK (length(trim(codigo)) > 0),
    nombre TEXT NOT NULL CHECK (length(trim(nombre)) > 0),
    descripcion TEXT NOT NULL CHECK (length(trim(descripcion)) > 0)
);

CREATE TABLE categorias_fuente_ruido (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE CHECK (length(trim(codigo)) > 0),
    nombre TEXT NOT NULL CHECK (length(trim(nombre)) > 0),
    descripcion TEXT NOT NULL CHECK (length(trim(descripcion)) > 0)
);

CREATE TABLE roles_usuario (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol TEXT NOT NULL UNIQUE CHECK (length(trim(nombre_rol)) > 0),
    descripcion TEXT NOT NULL CHECK (length(trim(descripcion)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tipos_fuente_ruido (
    id_tipo_fuente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE CHECK (codigo IN ('traffic', 'commerce', 'construction', 'entertainment', 'other')),
    nombre_fuente TEXT NOT NULL CHECK (length(trim(nombre_fuente)) > 0),
    id_categoria INTEGER NOT NULL REFERENCES categorias_fuente_ruido(id_categoria) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE estados_reporte (
    id_estado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_estado TEXT NOT NULL UNIQUE CHECK (codigo_estado = 'received'),
    descripcion TEXT NOT NULL CHECK (length(trim(descripcion)) > 0)
);

CREATE TABLE reportes_ciudadanos (
    id_reporte TEXT NOT NULL PRIMARY KEY CHECK (length(id_reporte) > 0),
    id_tipo_fuente INTEGER NOT NULL REFERENCES tipos_fuente_ruido(id_tipo_fuente) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_estado INTEGER NOT NULL REFERENCES estados_reporte(id_estado) ON DELETE RESTRICT ON UPDATE CASCADE,
    descripcion TEXT NOT NULL CHECK (length(descripcion) BETWEEN 10 AND 500),
    nivel_estimado_db DOUBLE PRECISION CHECK (nivel_estimado_db IS NULL OR nivel_estimado_db BETWEEN 30 AND 120),
    fecha_hora TIMESTAMPTZ NOT NULL,
    -- Identificador del lugar verificado. 'osm': N/W/R + número de OpenStreetMap.
    -- 'google': reportes anteriores a la versión 4, conservados sin cambios.
    id_lugar TEXT CHECK (id_lugar IS NULL OR id_lugar ~ '^[A-Za-z0-9_-]{1,255}$'),
    proveedor_lugar TEXT CHECK (proveedor_lugar IN ('google', 'osm')),
    es_historico BOOLEAN NOT NULL DEFAULT FALSE,
    ubicacion_heredada TEXT,
    CHECK (es_historico OR id_lugar IS NOT NULL),
    CHECK (es_historico OR ubicacion_heredada IS NULL),
    CONSTRAINT reportes_lugar_con_proveedor CHECK ((id_lugar IS NULL) = (proveedor_lugar IS NULL)),
    CONSTRAINT reportes_lugar_osm_valido CHECK (proveedor_lugar IS DISTINCT FROM 'osm' OR id_lugar ~ '^[NWR][0-9]{1,19}$')
);

CREATE TABLE puntos_criticos (
    id_punto TEXT NOT NULL PRIMARY KEY CHECK (length(id_punto) > 0),
    id_tipo_fuente INTEGER NOT NULL REFERENCES tipos_fuente_ruido(id_tipo_fuente) ON DELETE RESTRICT ON UPDATE CASCADE,
    nombre TEXT NOT NULL,
    area TEXT NOT NULL,
    id_distrito INTEGER REFERENCES distritos(id_distrito) ON DELETE RESTRICT ON UPDATE CASCADE,
    distrito_heredado TEXT,
    id_zonificacion INTEGER REFERENCES zonificaciones(id_zonificacion) ON DELETE RESTRICT ON UPDATE CASCADE,
    sector TEXT NOT NULL,
    nivel_db DOUBLE PRECISION NOT NULL,
    etiqueta_fuente TEXT NOT NULL,
    descripcion TEXT NOT NULL,
    franja_horaria TEXT NOT NULL,
    x DOUBLE PRECISION NOT NULL CHECK (x BETWEEN 0 AND 100),
    y DOUBLE PRECISION NOT NULL CHECK (y BETWEEN 0 AND 100),
    limite_referencia DOUBLE PRECISION NOT NULL,
    ilustrativo BOOLEAN NOT NULL DEFAULT TRUE,
    -- Posición aproximada de OpenStreetMap (ODbL); el nivel de ruido es ilustrativo.
    latitud DOUBLE PRECISION CHECK (latitud BETWEEN -90 AND 90),
    longitud DOUBLE PRECISION CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT puntos_coordenadas_completas CHECK ((latitud IS NULL) = (longitud IS NULL)),
    CHECK ((id_distrito IS NOT NULL AND distrito_heredado IS NULL) OR
           (id_distrito IS NULL AND distrito_heredado IS NOT NULL))
);

-- Cuentas de usuario. La ubicación territorial se obtiene solo a través del distrito
-- (distrito -> provincia -> departamento); no se duplican provincia ni departamento.
-- password_hash guarda un hash Argon2id; la contraseña en texto plano nunca se almacena.
CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER NOT NULL REFERENCES roles_usuario(id_rol) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_distrito INTEGER NOT NULL REFERENCES distritos(id_distrito) ON DELETE RESTRICT ON UPDATE CASCADE,
    nombres TEXT NOT NULL CHECK (length(trim(nombres)) BETWEEN 2 AND 80),
    apellidos TEXT NOT NULL CHECK (length(trim(apellidos)) BETWEEN 2 AND 80),
    telefono TEXT NOT NULL CHECK (telefono ~ '^[0-9+() -]{6,20}$'),
    direccion TEXT NOT NULL CHECK (length(trim(direccion)) BETWEEN 5 AND 200),
    nombre_usuario TEXT NOT NULL UNIQUE CHECK (nombre_usuario ~ '^[a-zA-Z0-9_.-]{3,40}$'),
    password_hash TEXT NOT NULL CHECK (length(trim(password_hash)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Impide cuentas que solo difieren en mayúsculas («Ana» y «ana»); el inicio de sesión busca sin distinguirlas.
CREATE UNIQUE INDEX usuarios_nombre_usuario_minusculas_unico ON usuarios (lower(nombre_usuario));
CREATE INDEX usuarios_id_rol_idx ON usuarios (id_rol);
CREATE INDEX usuarios_id_distrito_idx ON usuarios (id_distrito);

CREATE TABLE decibelcity_schema (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    version INTEGER NOT NULL CHECK (version > 0),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
