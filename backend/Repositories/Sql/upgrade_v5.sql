-- Migración v4 → v5: cuentas de usuario. Se ejecuta en la misma transacción del arranque,
-- bajo la cerradura de migraciones; un fallo revierte la actualización completa. No modifica datos existentes.
-- El rol base «ciudadano» lo asegura repositories/catalogs.py con ON CONFLICT DO NOTHING.
CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER NOT NULL REFERENCES roles_usuario(id_rol) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_distrito INTEGER NOT NULL REFERENCES distritos(id_distrito) ON DELETE RESTRICT ON UPDATE CASCADE,
    nombres TEXT NOT NULL CHECK (length(trim(nombres)) BETWEEN 2 AND 80),
    apellidos TEXT NOT NULL CHECK (length(trim(apellidos)) BETWEEN 2 AND 80),
    telefono TEXT NOT NULL CHECK (telefono ~ '^[0-9+() -]{6,20}$'),
    direccion TEXT NOT NULL CHECK (length(trim(direccion)) BETWEEN 5 AND 200),
    nombre_usuario TEXT NOT NULL UNIQUE CHECK (nombre_usuario ~ '^[a-zA-Z0-9_.-]{3,40}$'),
    password_hash TEXT NOT NULL CHECK (length(trim(password_hash)) > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Impide cuentas que solo difieren en mayúsculas («Ana» y «ana»); el inicio de sesión busca sin distinguirlas.
CREATE UNIQUE INDEX usuarios_nombre_usuario_minusculas_unico ON usuarios (lower(nombre_usuario));
CREATE INDEX usuarios_id_rol_idx ON usuarios (id_rol);
CREATE INDEX usuarios_id_distrito_idx ON usuarios (id_distrito);

UPDATE decibelcity_schema SET version = 5, applied_at = CURRENT_TIMESTAMP;
